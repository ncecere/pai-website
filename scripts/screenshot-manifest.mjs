// Writes SCREENSHOTS.md, the capture list for the demo installation, from
// lib/slots.json: for every slot the file the page expects, its shape and
// size, the persona, what it should show, and the alt text and caption the
// page uses (check them against the image after a capture). The status column
// reads lib/screenshots.json (filled by `npm run images`).
//
//   npm run manifest              write SCREENSHOTS.md
//   npm run manifest -- --check   fail if SCREENSHOTS.md is out of date (CI)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const slots = JSON.parse(readFileSync(join(root, "lib", "slots.json"), "utf8"));
const shots = JSON.parse(readFileSync(join(root, "lib", "screenshots.json"), "utf8"));
const target = join(root, "SCREENSHOTS.md");

const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");
const lines = [
  "# Screenshot slots",
  "",
  "<!-- Generated by `npm run manifest` from lib/slots.json; edit that file, not this one. -->",
  "",
  "The page has " + Object.keys(slots).length + " named screenshot slots. A slot without an image shows a marked",
  "placeholder naming the file it expects. The capture comes from a fictional demo installation of Pi Agent Interface,",
  "**Example Corp** at `chat.example.com`, with these people and agents:",
  "",
  "- **Priya Shah**, member (most slots). Agents: the provided **Assistant** and **Research**, and her own",
  "  **Release notes**. Conversations with plausible work titles, some working, done, failed, pinned and snoozed.",
  "- **Alex Morgan**, administrator (the Admin slots). Example Corp's other people: Sam Ortiz, Jordan Lee (suspended),",
  "  Maria Garcia.",
  "",
  "Desktop captures are 1440x900 (any 16:10 at that width or larger); `npm run images` resizes to 1600 px wide at most.",
  "Phone captures are 390x844 at 2x. Save them as PNG under the expected name in `../pai-assets/screenshots/` (or",
  "`SCREENSHOTS_DIR`), then run `npm run images && npm run og && npm run manifest` and commit.",
  "",
  "| File | Shape | Persona | What it should show | Status |",
  "|---|---|---|---|---|",
];
for (const [name, slot] of Object.entries(slots)) {
  const file = `${slot.file ?? name}.png`;
  const shape = slot.shape === "phone" ? "phone, 390x844 @2x" : "desktop, 1440x900";
  const status = shots[name] ? (shots[name].interim ? "interim" : "filled") : "placeholder";
  lines.push(`| \`${file}\` | ${shape} | ${cell(slot.persona ?? "")} | ${cell(slot.capture ?? "")} | ${status} |`);
}
lines.push("", "## Alt text and captions", "", "As the page uses them; update `lib/slots.json` if a capture differs.", "");
for (const [name, slot] of Object.entries(slots)) {
  lines.push(`### \`${name}\``, "", `- Alt: ${slot.alt}`, `- Caption: ${slot.caption}`, "");
}
const out = lines.join("\n");

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {}
  if (current !== out) {
    console.error("SCREENSHOTS.md is out of date: run `npm run manifest` and commit it.");
    process.exit(1);
  }
  console.log("SCREENSHOTS.md matches lib/slots.json");
} else {
  writeFileSync(target, out);
  console.log(`wrote SCREENSHOTS.md (${Object.keys(slots).length} slots)`);
}
